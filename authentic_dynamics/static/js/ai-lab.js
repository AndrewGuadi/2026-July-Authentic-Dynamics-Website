  function parseCSV(text){
    const result=[],row=[];let cell='',quoted=false;
    text=text.replace(/^\uFEFF/,'');for(let i=0;i<text.length;i++){
      const c=text[i];
      if(c==='"'){if(quoted&&text[i+1]==='"'){cell+='"';i++;}else if(!cell||quoted)quoted=!quoted;else cell+=c;}
      else if(c===','&&!quoted){row.push(cell);cell='';}
      else if((c==='\n'||c==='\r')&&!quoted){if(c==='\r'&&text[i+1]==='\n')i++;row.push(cell);if(row.some(Boolean))result.push([...row]);row.length=0;cell='';}
      else cell+=c;
    }
    if(quoted)throw Error('CSV contains an unterminated quoted field.');
    row.push(cell);if(row.some(Boolean))result.push([...row]);return result;
  }

  function forecast(root){
    shell(root,'<h3>Forecast a series and check a baseline.</h3><p class="ai-note">Paste daily or monthly values (date,value). This is a real chronological baseline and backtest, not Timestral or guaranteed financial advice.</p>'+
      area('csv','Dated CSV (date,value)','2026-01-01,120\n2026-01-02,128\n2026-01-03,130\n2026-01-04,125\n2026-01-05,138\n2026-01-06,145\n2026-01-07,144\n2026-01-08,154',14000)+
      '<div class="ai-grid"><label>Prediction method<select name="method"><option value="last">Last observed value</option><option value="mean">Recent 7-point mean</option><option value="season">Seasonal repeat</option></select></label>'+
      '<label>Horizon (points)<input name="horizon" type="number" min="1" max="30" value="7"></label>'+
      '<label>Seasonal period<input name="period" type="number" min="2" max="365" value="7"></label></div>'+
      '<div class="ai-actions">'+button('Run baseline')+button('Download predictions CSV','download',true)+'</div><div class="ai-preview" data-result></div>');
    let report='';
    const predicted=(series,i,method,period)=>{
      if(method==='mean')return series.slice(-Math.min(7,series.length)).reduce((a,b)=>a+b,0)/Math.min(7,series.length);
      if(method==='season'&&series.length>=period)return series[series.length-period];
      return series[series.length-1];
    };
    root.querySelector('[data-action=go]').addEventListener('click',wrap(root,()=>{
      const rows=parseCSV(value(root,'csv')).filter(r=>r.length>=2);
      const data=[];
      for(const row of rows){if(/date/i.test(row[0])&&/value|amount|sales/i.test(row[1]))continue;
        const d=row[0].trim(),v=Number(row[1].trim());
        if(!/^\d{4}-\d{2}-\d{2}$/.test(d)||!Number.isFinite(v)||v<0||!Number.isFinite(Date.parse(d+'T00:00:00Z')))throw Error('Use valid ISO dates and nonnegative numerical values.');
        data.push({date:d,value:v});}
      if(data.length<6||data.length>500)throw Error('Enter between 6 and 500 dated observations.');
      if(data.some((r,i)=>i&&r.date<=data[i-1].date))throw Error('Sort dates ascending and remove duplicates before forecasting.');
      const method=value(root,'method'),period=Number(value(root,'period')),horizon=Number(value(root,'horizon'));
      if(!(period>=2&&period<=365&&horizon>=1&&horizon<=30))throw Error('Choose a valid period and horizon.');
      if(method==='season'&&data.length<period+2)throw Error('Add more data than the seasonal period before forecasting.');
      const nums=data.map(d=>d.value);
      const nTest=Math.max(2,Math.min(20,Math.floor(nums.length*.2)));let err=0;
      for(let i=nums.length-nTest;i<nums.length;i++){
        const estimate=predicted(nums.slice(0,i),i,method,period);
        err+=Math.abs(estimate-nums[i]);
      }
      const forecastVals=[],history=[...nums];
      for(let i=0;i<horizon;i++){const val=predicted(history,history.length,method,period);
        forecastVals.push(val);history.push(val);}
      report='Step,Forecast\n'+forecastVals.map((v,i)=>(i+1)+','+v.toFixed(2)).join('\n');
      const result=output(root);result.replaceChildren();
      const p=document.createElement('p');p.textContent='Holdout MAE (last '+nTest+' observations): '+(err/nTest).toFixed(2)+'. This is baseline error on your history, not a guarantee.';result.append(p);
      const list=document.createElement('ol');list.className='ai-list';
      forecastVals.forEach((v,i)=>{const li=document.createElement('li');li.textContent='Step '+(i+1)+': '+v.toFixed(2);list.append(li);});result.append(list);
      notify(root,'Chronological baseline computed. Missing dates/seasonality must be reviewed separately.');
    }));
    root.querySelector('[data-action=download]').addEventListener('click',wrap(root,()=>{
      if(!report)throw Error('Run the forecast first.');save('baseline-forecast.csv',report,'text/csv;charset=utf-8');
    }));
  }

