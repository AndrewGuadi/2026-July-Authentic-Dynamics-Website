  function video(root){
    shell(root,'<h3>Create a short promotional video.</h3><p class="ai-note">This browser animates your own copy into a downloadable silent WebM video. It does not run LTX-2.5 or generate scenes using AI.</p>'+
      '<div class="ai-grid">'+line('business','Business name','text','Main Street')+line('first','Opening line','text','Your neighborhood favorite')+
      line('second','Second line','text','Here for your next project')+line('last','Ending call to action','text','Come visit us')+'</div>'+
      '<div class="ai-actions">'+button('Preview / render video')+button('Download WebM','download',true)+'</div><div class="ai-preview" data-result><canvas width="960" height="540" aria-label="Video frames"></canvas></div>');
    const canvas=root.querySelector('canvas'),ctx=canvas.getContext('2d');let blob=null,rendering=false;
    const frames=()=>[value(root,'first'),value(root,'second'),value(root,'last')].map(x=>limit(x||'Your story',80));
    function paint(progress,slides,business){
      const phase=Math.min(2,Math.floor(progress*3)),t=(progress*3)-phase;
      ctx.fillStyle='#0c0f0d';ctx.fillRect(0,0,960,540);ctx.fillStyle='#b8ff63';ctx.fillRect(50,46,72,7);
      ctx.fillStyle='#dadbd4';ctx.font='bold 23px Arial';ctx.fillText(limit(business||'AUTHENTIC DYNAMICS',40),50,95,850);
      const alpha=Math.max(0,Math.min(1,t*6,(1-t)*7));ctx.globalAlpha=alpha;
      ctx.fillStyle='#f5f5f0';ctx.font='bold 54px Arial';const parts=slides[phase].match(/.{1,27}(?:\s|$)/g)||[slides[phase]];
      parts.slice(0,3).forEach((s,i)=>ctx.fillText(s.trim(),50,215+i*66,860));ctx.globalAlpha=1;
      ctx.fillStyle='#b8ff63';ctx.fillRect(50,476,860*progress,5);
    }
    async function record(){
      if(rendering)throw Error('Rendering already in progress.');
      if(!canvas.captureStream||!window.MediaRecorder)throw Error('This browser cannot record a canvas video.');
      let mime=['video/webm;codecs=vp9','video/webm;codecs=vp8','video/webm'].find(m=>MediaRecorder.isTypeSupported(m));
      if(!mime)throw Error('WebM recording is unsupported in this browser.');
      const stream=canvas.captureStream(24),pieces=[];
      const recorder=new MediaRecorder(stream,{mimeType:mime,videoBitsPerSecond:2800000});
      const slides=frames(),business=value(root,'business');blob=null;rendering=true;notify(root,'Rendering a 6-second silent video…');
      const done=new Promise((resolve,reject)=>{recorder.ondataavailable=e=>{if(e.data.size)pieces.push(e.data)};
        recorder.onerror=()=>reject(Error('Recording failed.'));recorder.onstop=()=>resolve(new Blob(pieces,{type:mime}));});
      try{
        recorder.start();
        const started=performance.now();
        await new Promise(resolve=>{function tick(now){const progress=Math.min(1,(now-started)/6000);paint(progress,slides,business);
          if(progress<1)requestAnimationFrame(tick);else resolve();}requestAnimationFrame(tick);});
        recorder.stop();blob=await done;notify(root,'Video ready to download. Silent WebM, created entirely in your browser.');
      } finally {stream.getTracks().forEach(t=>t.stop());rendering=false;}
    }
    root.querySelector('[data-action=go]').addEventListener('click',wrap(root,record));
    root.querySelector('[data-action=download]').addEventListener('click',wrap(root,async()=>{
      if(!blob)await record();if(blob?.size)save('business-promo.webm',blob);else throw Error('No recording was produced.');
    }));
  }

  function cutout(root){
    shell(root,'<h3>Cut a product out of its background.</h3><p class="ai-note">Manual outline tool. Click/tap around the product, then export a transparent PNG containing unmodified original pixels. This is not SAM 3 segmentation.</p>'+
      '<label>Original product photo<input type="file" name="photo" accept="image/png,image/jpeg,image/webp"></label>'+
      '<div class="ai-actions">'+button('Undo last point','undo',true)+button('Clear selection','clear',true)+button('Export transparent PNG','download')+'</div>'+
      '<div class="ai-preview" data-result><canvas width="800" height="500" aria-label="Click points around the desired object"></canvas></div>');
    const canvas=root.querySelector('canvas'),ctx=canvas.getContext('2d');let image=null,points=[],display={x:0,y:0,w:1,h:1};
    const redraw=()=>{
      ctx.clearRect(0,0,canvas.width,canvas.height);ctx.fillStyle='#eeeeea';ctx.fillRect(0,0,canvas.width,canvas.height);
      if(!image)return;
      ctx.drawImage(image,display.x,display.y,display.w,display.h);
      if(points.length){ctx.lineWidth=3;ctx.strokeStyle='#b8ff63';ctx.fillStyle='#090909';ctx.beginPath();
        points.forEach((p,i)=>i?ctx.lineTo(p[0],p[1]):ctx.moveTo(p[0],p[1]));
        if(points.length>2)ctx.closePath();ctx.stroke();
        points.forEach(p=>{ctx.beginPath();ctx.arc(p[0],p[1],5,0,Math.PI*2);ctx.fill();ctx.stroke();});}
    };
    input(root,'photo').addEventListener('change',wrap(root,async()=>{
      const f=input(root,'photo').files[0];if(!f)return;
      if(image)image.close();image=await decode(f);points=[];
      const s=Math.min(800/image.width,500/image.height);display={w:image.width*s,h:image.height*s,x:(800-image.width*s)/2,y:(500-image.height*s)/2};
      redraw();notify(root,'Image loaded locally. Click around the product (at least three points).');
    }));
    canvas.addEventListener('pointerdown',e=>{
      if(!image)return;const box=canvas.getBoundingClientRect();
      const x=(e.clientX-box.left)*canvas.width/box.width,y=(e.clientY-box.top)*canvas.height/box.height;
      if(x<display.x||x>display.x+display.w||y<display.y||y>display.y+display.h)return;
      if(points.length>=200)return notify(root,'Maximum 200 outline points reached.',true);
      points.push([x,y]);redraw();notify(root,points.length+' outline points. Close the shape automatically at export.');
    });
    root.querySelector('[data-action=undo]').addEventListener('click',()=>{points.pop();redraw();});
    root.querySelector('[data-action=clear]').addEventListener('click',()=>{points=[];redraw();notify(root,'Selection cleared.');});
    root.querySelector('[data-action=download]').addEventListener('click',wrap(root,async()=>{
      if(!image||points.length<3)throw Error('Load a photo and choose at least three outline points.');
      const exportCanvas=document.createElement('canvas');exportCanvas.width=image.width;exportCanvas.height=image.height;
      const c=exportCanvas.getContext('2d');c.beginPath();
      points.forEach((p,i)=>{const xx=(p[0]-display.x)/display.w*image.width,yy=(p[1]-display.y)/display.h*image.height;
        if(!i)c.moveTo(xx,yy);else c.lineTo(xx,yy);});c.closePath();c.clip();c.drawImage(image,0,0);
      const png=await new Promise(resolve=>exportCanvas.toBlob(resolve,'image/png'));if(!png)throw Error('PNG export failed.');
      save('product-cutout.png',png);notify(root,'Transparent PNG exported. Inspect the edges before publishing.');
    }));
  }

