const { chromium } = require('playwright');
const assert = require('node:assert/strict');
// Run against an isolated migrated app with an enrolled test login.
const base = process.env.HUB_BASE_URL || 'http://127.0.0.1:5058';
(async () => {
  const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/hub`);
  await page.getByLabel('Email address').fill(process.env.HUB_TEST_EMAIL || 'preview@example.test');
  await page.getByLabel('Password', {exact:true}).fill(process.env.HUB_TEST_PASSWORD || 'preview-password-only');
  await page.getByRole('button', {name:/Sign in/}).click();
  await page.waitForURL('**/hub');
  await page.screenshot({path:'/tmp/ad-browser/hub-dashboard.png',fullPage:true});
  await page.getByRole('link',{name:'+ Add business'}).click();
  await page.getByLabel('Name', {exact:false}).first().fill('Browser workflow client');
  await page.getByRole('button',{name:'Save record'}).click();
  await page.waitForURL(/\/hub\/businesses\/[^/]+$/);
  assert(await page.getByRole('heading',{name:'Browser workflow client',exact:true}).count());
  await page.locator('.hub-related').filter({has:page.getByRole('heading',{name:'Projects',exact:true})}).getByRole('link',{name:'+ Add',exact:true}).click();
  await page.getByLabel('Title').fill('Browser website');
  await page.getByRole('button',{name:'Save record'}).click();
  await page.getByRole('button',{name:'Apply website project template'}).click();
  await page.getByRole('link',{name:'Open project board'}).click();
  await page.waitForURL('**/board');
  const card = page.locator('.hub-card').filter({hasText:'Discovery call'});
  const target = page.locator('.hub-lane').filter({has:page.getByRole('heading',{name:'Build',exact:true})});
  await card.dragTo(target);
  await page.getByRole('status').filter({hasText:'Move saved.'}).waitFor();
  await page.reload();
  assert(await target.locator('.hub-card').filter({hasText:'Discovery call'}).count());
  await page.screenshot({path:'/tmp/ad-browser/hub-board.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.goto(`${base}/hub`);
  await page.screenshot({path:'/tmp/ad-browser/hub-mobile.png',fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth));
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('Browser checks passed: existing login flow, business form, project template, saved drag move, reload persistence, mobile width, no JS errors.');
})().catch(error=>{console.error(error);process.exit(1);});
