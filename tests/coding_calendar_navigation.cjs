const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const base = process.env.CODING_BASE_URL || 'http://127.0.0.1:5073';
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CODING_CHROMIUM_PATH ? { executablePath: process.env.CODING_CHROMIUM_PATH } : {}) });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.clock.install({ time: new Date('2026-10-24T12:00:00-04:00') });
    await page.goto(base + '/coding-calendar/');
    assert.equal(await page.locator('#calendar-date').inputValue(), '2026-10-24');
    assert.equal(await page.locator('[role=tabpanel]:visible').count(), 1);
    const js = page.locator('#calendar-tab-javascript'), py = page.locator('#calendar-tab-python'), sql = page.locator('#calendar-tab-sql');
    await js.focus(); await page.keyboard.press('ArrowRight');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'calendar-tab-python');
    assert.equal(await js.getAttribute('aria-selected'), 'true'); // Manual activation.
    await page.keyboard.press('Enter');
    assert.equal(await py.getAttribute('aria-selected'), 'true');
    assert.ok(await page.locator('#calendar-panel-python').isVisible());
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'calendar-panel-python');
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'calendar-tab-python');
    await page.keyboard.press('End');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'calendar-tab-sql');
    await page.keyboard.press('Space'); assert.equal(await sql.getAttribute('aria-selected'), 'true');
    await page.keyboard.press('Home'); assert.equal(await page.evaluate(() => document.activeElement.id), 'calendar-tab-javascript');
    await page.keyboard.press('ArrowLeft'); assert.equal(await page.evaluate(() => document.activeElement.id), 'calendar-tab-sql');
    await py.click();
    await page.locator('#calendar-next').click();
    await page.waitForURL(/date=2026-10-25/);
    assert.equal(await page.locator('#calendar-date').inputValue(), '2026-10-25');
    assert.equal(await py.getAttribute('aria-selected'), 'true');
    assert.match(await page.locator('#calendar-panel-python').textContent(), /Available on 2026-10-25/);
    assert.equal(await page.locator('#calendar-panel-python a[href*="2026-10-25"]').count(), 0);
    await page.locator('#calendar-today').click();
    assert.equal(await page.locator('#calendar-date').inputValue(), '2026-10-24');
    assert.equal(new URL(page.url()).searchParams.has('date'), false);
    await page.locator('#calendar-date').fill('2026-10-22');
    await page.getByRole('button', { name: 'Go to date', exact: true }).click();
    await page.waitForURL(/date=2026-10-22/);
    assert.match(await page.locator('#calendar-panel-python').textContent(), /str.lower/);
    await page.locator('#archive-category').selectOption('strings');
    await page.locator('#archive-track').selectOption('python');
    await page.locator('#archive-level').selectOption('beginner');
    await page.locator('#archive-month').selectOption('2026-10');
    await page.getByRole('button', { name: 'Filter archive' }).click();
    await page.waitForURL(/category=strings/);
    assert.ok(await page.locator('.calendar-table tbody tr').count() >= 2);
    assert.ok(await page.locator('.calendar-table td a').evaluateAll(links => links.every(link => link.href.includes('/python/'))));
    assert.match(await page.locator('.calendar-table').textContent(), /str.lower/);
    assert.doesNotMatch(await page.locator('.calendar-table').textContent(), /String.trim/);
    await page.goto(base + '/coding-calendar/javascript/2026-10-23/');
    assert.match(await page.locator('#lesson-previous').getAttribute('href'), /2026-10-22/);
    assert.match(await page.locator('#lesson-next').getAttribute('href'), /2026-10-24/);
    assert.equal(await page.locator('.lesson-language-links a').count(), 3);
    await page.locator('.lesson-language-links a').filter({ hasText: 'Python' }).click();
    await page.waitForURL(/python\/2026-10-23/);
    await page.goto(base + '/coding-calendar/');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.equal(await page.locator('#calendar-previous').isVisible(), true);
    assert.ok(await page.locator('.calendar-date-nav, .calendar-pagination').evaluateAll(items => items.every(item => getComputedStyle(item).position === 'static')));
    assert.ok(await page.evaluate(() => document.querySelector('.calendar-date-nav').getBoundingClientRect().top >= document.querySelector('#calendar-date-heading').getBoundingClientRect().bottom));
    await page.locator('.calendar-table-scroll').focus();
    await page.keyboard.press('ArrowRight');
    await page.waitForFunction(() => document.querySelector('.calendar-table-scroll').scrollLeft > 0);
    await page.waitForTimeout(250); // Let the browser's native keyboard scroll animation finish.
    await page.locator('.calendar-table-scroll').evaluate(el => { el.scrollTo({ left: 0, behavior: 'instant' }); el.blur(); });
    await page.waitForFunction(() => document.querySelector('.calendar-table-scroll').scrollLeft === 0);
    assert.equal(await page.locator('[tabindex]').evaluateAll(items => items.some(item => Number(item.getAttribute('tabindex')) > 0)), false);
    await page.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; window.scrollTo(0, 0); document.activeElement?.blur(); });
    await page.waitForFunction(() => scrollY === 0);
    await page.screenshot({ path: '/tmp/calendar-navigation-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: '/tmp/calendar-navigation-desktop.png', fullPage: true });
    // An explicitly browsed date survives midnight instead of being reset.
    await page.goto(base + '/coding-calendar/?date=2026-10-22');
    await page.clock.setSystemTime(new Date('2026-10-25T01:00:00-04:00'));
    await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
    assert.equal(await page.locator('#calendar-date').inputValue(), '2026-10-22');
    assert.deepEqual(errors, []);
    console.log('PASS actual-date default, manual keyboard tabs, wrap/Home/End, focus exit, date picker, previous/next, Today reset, language retention, future scheduling, categorized archive, lesson navigation, mobile layout');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
